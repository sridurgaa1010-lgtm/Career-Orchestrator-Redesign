-- INDEX 1: USERS - Unique Email Index (Primary Lookup)
CREATE INDEX CAREER_ORCHESTRATOR.USERS_EMAIL_IDX
    ON CAREER_ORCHESTRATOR.USERS (email);

COMMENT ON INDEX CAREER_ORCHESTRATOR.USERS_EMAIL_IDX
    IS 'Index on USERS.email for fast email-based user lookups.';

-- INDEX 2: USERS - Full Name Search
CREATE INDEX CAREER_ORCHESTRATOR.USERS_NAME_IDX
    ON CAREER_ORCHESTRATOR.USERS (last_name, first_name);

COMMENT ON INDEX CAREER_ORCHESTRATOR.USERS_NAME_IDX
    IS 'Composite index on USERS.last_name, first_name for name-based searches.';

